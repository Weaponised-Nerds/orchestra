"""
Local Cloud-Liberation DNS Sinkhole & Telemetry Interceptor.

Mitigates Pitfall 2 (Vendor Firmware Breakage & Cloud Hostility) and enables
Fake-Cloud AP activation for Tuya/Sensibo hardware by redirecting vendor cloud
activation domains to the local Zenith Micro-Node IP while blocking unsolicited
OTA firmware updates that could disable local ports.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class DNSInterceptRule:
    """Represents a local DNS override or sinkhole entry on the Z-Node."""

    domain: str
    action: str  # "redirect_to_znode" | "sinkhole_nxdomain"
    target_ip: str
    reason: str


class LocalCloudBlocker:
    """
    Manages local dnsmasq / hosts redirection rules so cloud-tethered appliances
    (e.g., Tuya smart plugs, Sensibo controllers, EV chargers) activate against
    Orchestra's local liberation endpoints and cannot phone home to break local APIs.
    """

    def __init__(self, node_local_ip: str = "192.168.1.250") -> None:
        self.node_local_ip = node_local_ip
        self.rules: dict[str, DNSInterceptRule] = {}
        self._seed_default_liberation_rules()

    def _seed_default_liberation_rules(self) -> None:
        # 1. Tuya Fake-Cloud Activation Redirects (intercepts initial pairing to issue local_key)
        tuya_activation_domains = [
            "a.tuya.com",
            "a.tuyaeu.com",
            "a.tuyaus.com",
            "a.tuyacn.com",
            "m2.tuya.com",
            "m2.tuyaeu.com",
            "m2.tuyaus.com",
        ]
        for dom in tuya_activation_domains:
            self.add_redirect_rule(
                dom,
                reason="Intercept Tuya AP/EZ-mode activation to synthesize local_key without Tuya Cloud account",
            )

        # 2. Vendor OTA Firmware Lockout Protection (prevents cloud updates from closing local ports)
        ota_lockout_domains = [
            "ota.tuya.com",
            "firmware.sensibo.com",
            "ota.myair.com.au",
            "rheem.clearblade.com",
            "ota.rinnai.com.au",
        ]
        for dom in ota_lockout_domains:
            self.add_sinkhole_rule(
                dom,
                reason="Prevent unsolicited vendor OTA updates that disable local TCP/HTTP APIs (Pitfall 2)",
            )

    def add_redirect_rule(self, domain: str, reason: str) -> None:
        """Redirect a vendor cloud domain to the local Z-Node IP."""
        self.rules[domain] = DNSInterceptRule(
            domain=domain,
            action="redirect_to_znode",
            target_ip=self.node_local_ip,
            reason=reason,
        )

    def add_sinkhole_rule(self, domain: str, reason: str) -> None:
        """Sinkhole a vendor telemetry/OTA domain to 0.0.0.0."""
        self.rules[domain] = DNSInterceptRule(
            domain=domain,
            action="sinkhole_nxdomain",
            target_ip="0.0.0.0",
            reason=reason,
        )

    def register_hardware_domains(self, domains: list[str], redirect: bool = False) -> None:
        """Register domains from a discovered hardware device."""
        for dom in domains:
            if dom not in self.rules:
                if redirect:
                    self.add_redirect_rule(dom, reason="Hardware local activation redirect")
                else:
                    self.add_sinkhole_rule(dom, reason="Hardware cloud isolation sinkhole")

    def render_dnsmasq_conf(self) -> str:
        """Generate a valid dnsmasq configuration block for the Z-Node network interface."""
        lines = [
            "# Auto-generated by Zenith Orchestra LocalCloudBlocker",
            "# Redirects cloud activation to Z-Node and blocks hostile vendor OTA updates",
        ]
        for rule in self.rules.values():
            lines.append(f"# {rule.reason}")
            lines.append(f"address=/{rule.domain}/{rule.target_ip}")
        return "\n".join(lines) + "\n"
